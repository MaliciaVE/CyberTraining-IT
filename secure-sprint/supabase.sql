-- Run this in the Supabase SQL Editor for a shared public leaderboard.
create table if not exists public.secure_sprint_scores (
  id bigint generated by default as identity primary key,
  nickname varchar(18) not null check (char_length(nickname) between 1 and 18),
  score integer not null check (score between 0 and 10000),
  rank varchar(40) not null,
  created_at timestamptz not null default now()
);

alter table public.secure_sprint_scores enable row level security;

create policy "Public can read secure sprint scores"
on public.secure_sprint_scores for select
to anon using (true);

create policy "Public can add secure sprint scores"
on public.secure_sprint_scores for insert
to anon with check (
  char_length(nickname) between 1 and 18
  and score between 0 and 10000
);

create index if not exists secure_sprint_scores_score_idx
on public.secure_sprint_scores (score desc);
